### Utility Functions for Loading Statistics from JSON ###

def load_statistics_from_json(json_path):
    """
    Load statistics from a JSON file generated by calculate_std_mean.py
    
    Args:
        json_path: Path to the JSON file containing statistics
        
    Returns:
        dict: Dictionary containing mean, std, min, max as numpy arrays,
              and optionally num_episodes from metadata
    """
    with open(json_path, 'r') as f:
        data = json.load(f)
    
    stats = data.get('statistics', {})
    metadata = data.get('metadata', {})
    
    result = {
        'mean': np.array(stats.get('mean', [])),
        'std': np.array(stats.get('std', [])),
        'min': np.array(stats.get('min', [])),
        'max': np.array(stats.get('max', []))
    }
    
    # Add num_episodes if available in metadata
    if 'num_episodes' in metadata:
        result['num_episodes'] = metadata['num_episodes']
    
    return result


def create_task_config_from_json(
    task_name,
    json_path,
    dataset_dir,
    tissue_ids,
    tissue_ids_val=None,
    num_episodes=None,
    num_episodes_val=0,
    phantom=False,
    use_auto_label=False,
    goal_condition_style=None,
    no_qpos=False,
    camera_file_suffixes=None,
    episode_len=500,
    cutting_action_pad_size=0,
    recovery_ratio=1.0,
    norm_scheme='std',
    save_frequency=50,
    camera_names=None,
    merging_subtasks=False
):
    """
    Create a task configuration dictionary from a JSON statistics file.
    
    Args:
        task_name: Name for the task configuration
        json_path: Path to JSON file with statistics
        dataset_dir: Path to dataset directory
        tissue_ids: List of tissue sample IDs for training
        tissue_ids_val: List of tissue sample IDs for validation
        num_episodes: Number of training episodes (if None, will try to use from JSON)
        num_episodes_val: Number of validation episodes
        phantom: Whether using phantom data
        use_auto_label: Whether to use auto labeling
        goal_condition_style: Goal conditioning style (e.g., 'map', 'mask', 'dot')
        no_qpos: True for SRT, False for ACT
        camera_file_suffixes: List of camera file suffixes
        episode_len: Length of episodes
        cutting_action_pad_size: Padding size for cutting actions
        recovery_ratio: Recovery ratio
        norm_scheme: Normalization scheme
        save_frequency: Checkpoint save frequency
        camera_names: List of camera names
        merging_subtasks: Whether to merge subtasks
        
    Returns:
        dict: Task configuration dictionary
    """
    # Load statistics from JSON
    stats = load_statistics_from_json(json_path)
    
    # Use num_episodes from JSON if not provided and available
    if num_episodes is None and 'num_episodes' in stats:
        num_episodes = stats['num_episodes']
        print(f"Using num_episodes from JSON: {num_episodes}")
    
    # Set defaults
    if tissue_ids_val is None:
        tissue_ids_val = []
    if camera_file_suffixes is None:
        camera_file_suffixes = ["_left.jpg", "_psm1.jpg", "_psm2.jpg"]
    if camera_names is None:
        camera_names = ['left', 'left_wrist', 'right_wrist']
    
    # Build task config
    config = {
        'dataset_dir': dataset_dir,
        'phantom': phantom,
        'use_auto_label': use_auto_label,
        'no_qpos': no_qpos,
        'tissue_samples_ids': tissue_ids,
        'tissue_samples_ids_val': tissue_ids_val,
        'camera_file_suffixes': camera_file_suffixes,
        'episode_len': episode_len,
        'cutting_action_pad_size': cutting_action_pad_size,
        'recovery_ratio': recovery_ratio,
        'action_mode': ['hybrid', {
            'max_': stats['max'],
            'min_': stats['min'],
            'mean': stats['mean'],
            'std': stats['std']
        }],
        'norm_scheme': norm_scheme,
        'save_frequency': save_frequency,
        'camera_names': camera_names,
        'merging_subtasks': merging_subtasks,
    }
    
    # Add optional fields
    if num_episodes is not None:
        config['num_episodes'] = num_episodes
    if num_episodes_val is not None:
        config['num_episodes_val'] = num_episodes_val
    if goal_condition_style is not None:
        config['goal_condition_style'] = goal_condition_style
    
    return config


def add_task_config_from_json(task_name, json_path, **kwargs):
    """
    Create a task config from JSON and add it to TASK_CONFIGS.
    
    Args:
        task_name: Name for the new task configuration
        json_path: Path to JSON file with statistics
        **kwargs: Additional arguments to pass to create_task_config_from_json
        
    Example:
        add_task_config_from_json(
            'my_new_task',
            './std_mean_invivo.json',
            dataset_dir="/path/to/data",
            tissue_ids=[1, 2, 3],
            num_episodes=1000
        )
    """
    config = create_task_config_from_json(task_name, json_path, **kwargs)
    TASK_CONFIGS[task_name] = config
    print(f"Added task config '{task_name}' from {json_path}")
    return config


